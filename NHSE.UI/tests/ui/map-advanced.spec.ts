for (const width of [800, 390]) {
  test(`scaled drag brush cancels pointer loss and maps cells at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    const map = await openMap(page);
    await map.getByRole('spinbutton', { name: '高度', exact: true }).fill('2');
    await map.locator('.map-brush summary').click();
    await map.getByRole('checkbox', { name: '拖拽地形笔刷', exact: true }).check();
    const grid = map.locator('.map-grid'); await grid.scrollIntoViewIfNeeded();
    const box = (await grid.boundingBox())!;
    const start = { x: box.x + box.width / 32, y: box.y + box.height / 32 };
    await page.mouse.move(start.x, start.y); await page.mouse.down();
    await grid.dispatchEvent('pointercancel', { pointerId: 1 }); await page.mouse.up();
    expect(await payloads(page, 'paintMapStroke')).toHaveLength(0);
    await page.mouse.move(start.x, start.y); await page.mouse.down();
    await page.mouse.move(box.x + box.width * 2.5 / 16, start.y); await page.mouse.up();
    await expect.poll(async () => (await payloads(page, 'paintMapStroke')).length).toBe(1);
    expect((await payloads(page, 'paintMapStroke'))[0]).toMatchObject({ points: [{ x: 0, y: 0 }, { x: 1, y: 0 }, { x: 2, y: 0 }], values: { 'Map.Elevation': 2 } });
  });
}

import { test, expect, type Page } from '@playwright/test';
import { mockHost } from './mock-host';
async function openMap(page: Page) {
  await mockHost(page); await page.goto('/');
  await page.getByRole('button', { name: '打开存档', exact: true }).click();
  await page.locator('.sidebar nav').getByRole('button', { name: '地图与建筑', exact: true }).click();
  return page.locator('.map-page');
}
const payloads = (page: Page, command: string) => page.evaluate(command => (window as unknown as { nhseTestPayloads: { command: string; payload: Record<string, unknown> }[] }).nhseTestPayloads.filter(m => m.command === command).map(m => m.payload), command);
test('drag brush interpolates one stroke, cancels on Escape and keeps template out of navigation writes', async ({ page }) => {
  const map = await openMap(page);
  await map.getByRole('spinbutton', { name: '高度', exact: true }).fill('3');
  await map.locator('.map-brush summary').click();
  await map.getByRole('checkbox', { name: '拖拽地形笔刷', exact: true }).check();
  const grid = map.locator('.map-grid');
  await grid.scrollIntoViewIfNeeded();
  let box = (await grid.boundingBox())!;
  await page.mouse.move(box.x + box.width / 32, box.y + box.height / 32);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * 3.5 / 16, box.y + box.height / 32);
  await expect(grid.locator('.stroke-preview')).toHaveCount(4);
  await page.mouse.up();
  await expect.poll(async () => (await payloads(page, 'paintMapStroke')).length).toBe(1);
  expect((await payloads(page, 'paintMapStroke'))[0]).toMatchObject({ radius: 1, points: [{ x: 0, y: 0 }, { x: 1, y: 0 }, { x: 2, y: 0 }, { x: 3, y: 0 }], values: { 'Map.Elevation': 3 } });
  await expect(map.getByRole('spinbutton', { name: '高度', exact: true })).toHaveValue('3');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(page.getByRole('button', { name: '撤销', exact: true })).toBeDisabled();
  await grid.scrollIntoViewIfNeeded(); box = (await grid.boundingBox())!;
  await page.mouse.move(box.x + box.width / 32, box.y + box.height / 32); await page.mouse.down();
  await page.keyboard.press('Escape'); await page.mouse.up();
  expect(await payloads(page, 'paintMapStroke')).toHaveLength(1);
  await map.getByRole('combobox', { name: '预设类别', exact: true }).selectOption('water');
  await map.getByRole('button', { name: '地形预设 5', exact: true }).click();
  await expect(map.getByRole('combobox', { name: '地形形状', exact: true })).toHaveValue('21');
  await map.getByRole('button', { name: '建筑', exact: true }).click();
  expect(await payloads(page, 'editMap')).toHaveLength(0);
});
